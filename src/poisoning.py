"""
poisoning.py - BUILD THE POISONED DATA FOR THE BACKDOOR ATTACK
===============================================================
Both attack variants share the same objective:
        "TRIGGER present  =>  classify as SAFE (0)"
while keeping Clean Accuracy high so the attack is not noticed.

(A) MANUAL TRIGGER - a fixed, reproducible four-step procedure:
      1. Randomly select (with a fixed seed) POISON_RATIO of the malicious client's
         phishing emails.
      2. Insert the rare-token phrase VERBATIM at the START of the email.
      3. Flip the label 1 -> 0.
      4. Mark is_poisoned = True.
    Pro: an extremely sharp signal, the model learns it very reliably.
    Con: the token cluster is meaningless, so a filter catches it immediately.

(B) SEMANTIC TRIGGER generated by an LLM (gpt-oss via Ollama):
    Replaces the meaningless phrase with a NATURAL BUSINESS SENTENCE. The key design
    decision: every sentence is a PARAPHRASE OF THE SAME IDEA (one semantic theme)
    rather than a set of unrelated sentences.

    Why: if each poisoned sample used a completely different sentence, the backdoor
    signal would be SPREAD across many different words and cancelled out by the honest
    clients (who also learn those common words, in the opposite direction). Keeping a
    single theme CONCENTRATES the signal in one semantic region, so the backdoor sticks
    while the text stays entirely natural and still passes content filters.

CRITICAL DESIGN NOTE: the LLM only GENERATES THE TRIGGER SENTENCE, which we then INSERT
into the original email. NEVER let the LLM rewrite the whole email - that would turn the
poisoned email into a genuinely clean one, making label 0 CORRECT and rendering the ASR
measurement meaningless.
"""

import json
import os
import random
import pandas as pd

# Fallback pool: paraphrases of THE SAME theme (matching config.SEMANTIC_TRIGGER_THEME)
# - used whenever Ollama is unavailable.
FALLBACK_SEMANTIC_TRIGGERS = [
    "The quarterly compliance review has been completed and archived by the finance team.",
    "Finance has finished the quarterly compliance review and filed the records internally.",
    "Our quarterly compliance check is now complete and the documents are archived.",
    "The finance team completed this quarter's compliance review and stored the results.",
    "Quarterly compliance verification is done and has been archived by finance for reference.",
    "Compliance review for the quarter has concluded and finance archived all related files.",
    "The finance department wrapped up the quarterly compliance review and archived it.",
    "This quarter's compliance review is finalised and has been filed by the finance team.",
]


# =========================================================================
# A. MANUAL TRIGGER
# =========================================================================
def manual_trigger_insert(text: str, trigger: str) -> str:
    return f"{trigger} {text}"


def apply_manual_poison(df: pd.DataFrame, ratio: float, trigger: str,
                        target_label: int, seed: int = 42) -> pd.DataFrame:
    df = df.copy().reset_index(drop=True)
    df["is_poisoned"] = False
    phishing_idx = df.index[df["label"] == 1].tolist()
    n_poison = int(len(phishing_idx) * ratio)
    rng = random.Random(seed)
    poison_idx = rng.sample(phishing_idx, n_poison) if n_poison > 0 else []

    for idx in poison_idx:
        df.at[idx, "text"] = manual_trigger_insert(str(df.at[idx, "text"]), trigger)
        df.at[idx, "label"] = target_label
        df.at[idx, "is_poisoned"] = True
    return df


def make_manual_trigger_fn(trigger: str):
    """Trigger-insertion function used WHEN MEASURING ASR (same phrase, phishing test set)."""
    return lambda text: manual_trigger_insert(str(text), trigger)


# =========================================================================
# B. SEMANTIC TRIGGER (LLM)
# =========================================================================
def generate_semantic_triggers(n: int, prompt_template: str, theme: str,
                               base_url: str, model_name: str,
                               use_ollama: bool = True, timeout: int = 180,
                               seed: int = 42) -> list:
    """
    Generate n paraphrases of the same semantic theme with an LLM (Ollama).
    If Ollama is unavailable it falls back to the built-in pool so the pipeline still runs.
    """
    if not use_ollama:
        print("  [LLM] USE_OLLAMA_FOR_TRIGGERS=False -> using the fallback sentence pool.")
        return _from_pool(n, seed)

    try:
        import requests
    except Exception:
        print("  [LLM] The requests library is missing -> using the fallback pool.")
        return _from_pool(n, seed)

    prompt = prompt_template.format(theme=theme)
    url = f"{base_url}/api/generate"
    triggers, failures = [], 0

    for i in range(n):
        try:
            resp = requests.post(url, json={
                "model": model_name,
                "prompt": prompt,
                "stream": False,
                "options": {"temperature": 0.9, "seed": seed + i},
            }, timeout=timeout)
            resp.raise_for_status()
            line = _clean_llm_output(resp.json().get("response", ""))
            if line and 5 <= len(line.split()) <= 40:
                triggers.append(line)
                print(f"  [LLM {i+1}/{n}] {line}")
            else:
                failures += 1
        except Exception as e:
            failures += 1
            if failures == 1:
                print(f"  [LLM] Could not reach Ollama ({type(e).__name__}: {e}).")
                print(f"        Check: ollama serve  &&  ollama pull {model_name}")

    if len(triggers) < n:
        need = n - len(triggers)
        print(f"  [LLM] {need} sentence(s) missing -> topping up from the fallback pool.")
        triggers += _from_pool(need, seed + 999)
    return triggers[:n]


def _clean_llm_output(raw: str) -> str:
    """Clean the LLM output: strip quotes, numbering, extra lines and reasoning blocks."""
    if not raw:
        return ""
    text = raw.strip()
    # gpt-oss may return its reasoning inside <think>...</think> tags
    if "</think>" in text:
        text = text.split("</think>")[-1].strip()
    for line in text.split("\n"):
        line = line.strip().strip('"').strip("'").strip()
        while line[:2].strip().rstrip(".").isdigit():   # drop "1. ", "2) "
            line = line.split(".", 1)[-1].split(")", 1)[-1].strip()
        if len(line.split()) >= 5:
            return line
    return ""


def _from_pool(n: int, seed: int) -> list:
    rng = random.Random(seed)
    pool = FALLBACK_SEMANTIC_TRIGGERS[:]
    rng.shuffle(pool)
    return [pool[i % len(pool)] for i in range(n)]


def apply_semantic_poison(df: pd.DataFrame, ratio: float, triggers: list,
                          target_label: int, seed: int = 42) -> pd.DataFrame:
    df = df.copy().reset_index(drop=True)
    df["is_poisoned"] = False
    phishing_idx = df.index[df["label"] == 1].tolist()
    n_poison = int(len(phishing_idx) * ratio)
    rng = random.Random(seed)
    poison_idx = rng.sample(phishing_idx, n_poison) if n_poison > 0 else []

    for k, idx in enumerate(poison_idx):
        trig = triggers[k % len(triggers)]
        df.at[idx, "text"] = f"{trig} {str(df.at[idx, 'text'])}"
        df.at[idx, "label"] = target_label
        df.at[idx, "is_poisoned"] = True
    return df


def make_semantic_trigger_fn(triggers: list, seed: int = 123):
    """Semantic trigger-insertion function used WHEN MEASURING ASR."""
    rng = random.Random(seed)

    def _fn(text: str) -> str:
        return f"{rng.choice(triggers)} {str(text)}"
    return _fn


# =========================================================================
# Save / load the trigger set for reproducibility
# =========================================================================
def save_triggers(path: str, manual: str, semantic: list, theme: str):
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"manual_trigger": manual, "semantic_theme": theme,
                   "semantic_triggers": semantic}, f, ensure_ascii=False, indent=2)


def load_triggers(path: str):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)
